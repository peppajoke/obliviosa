#!/usr/bin/env python3
"""Build the players' journal from player/entries.json.

Writes player/dist/ (index.html, things.js, img/) containing ONLY the approved
player-facing entries. Nothing from codex/things.js is copied: the DM codex
never leaves this repo. Fails on unknown fields, missing images, or any
leak-guard term from secrets.txt that the entry has not explicitly allowed.

Usage: python3 player/build.py [--out DIR]
"""
import json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FIELDS = {"id", "name", "aliases", "type", "summary", "details", "images", "related", "seen", "forgotten", "allow", "status", "links"}
STATUSES = {"live", "staged"}
TYPES = {"person", "place", "item", "faction", "event", "monster", "spell", "document", "concept", "quest"}
FORGOTTEN_NAME = "▒▒▒▒▒▒▒▒"


def fail(msgs):
    for m in msgs:
        print("ERROR:", m, file=sys.stderr)
    sys.exit(1)


def main():
    out = os.path.join(HERE, "dist")
    if "--out" in sys.argv:
        out = os.path.abspath(sys.argv[sys.argv.index("--out") + 1])
    cfg = json.load(open(os.path.join(HERE, "config.json")))
    entries = json.load(open(os.path.join(HERE, "entries.json")))
    live_ids = set()
    lp = os.path.join(HERE, "live.txt")
    if os.path.isfile(lp):
        live_ids = {l.strip() for l in open(lp) if l.strip() and not l.startswith("#")}
    terms = [l.strip() for l in open(os.path.join(HERE, "secrets.txt")) if l.strip() and not l.startswith("#")]

    errors, ids = [], set()
    for e in entries:
        eid = e.get("id", "?")
        if eid in ids:
            errors.append(f"{eid}: duplicate id")
        ids.add(eid)
        for k in e:
            if k not in FIELDS:
                errors.append(f"{eid}: unknown field '{k}'")
        for k in ("id", "name", "type", "summary"):
            if not e.get(k):
                errors.append(f"{eid}: missing {k}")
        if e.get("status", "live") not in STATUSES:
            errors.append(f"{eid}: bad status {e.get('status')!r} (live or staged)")
        if e.get("type") not in TYPES:
            errors.append(f"{eid}: bad type {e.get('type')!r}")
        for im in e.get("images", []):
            if not os.path.isfile(os.path.join(ROOT, "codex", im["src"])):
                errors.append(f"{eid}: image not found codex/{im['src']}")
        if e.get("forgotten"):
            continue
        text = " ".join(str(e.get(k, "")) for k in ("id", "name", "summary", "details", "seen")).replace("-", " ") + " " + " ".join(e.get("aliases", [])) \
            + " " + " ".join(im.get("caption", "") for im in e.get("images", []))
        allowed = {a.lower() for a in e.get("allow", [])}
        for t in terms:
            if t.lower() not in allowed and re.search(r"(?<![a-z])" + re.escape(t.lower()) + r"(?![a-z])", text.lower()):
                errors.append(f"{eid}: contains leak-guard term '{t}' (add it to this entry's \"allow\" only if Jack approved the reveal)")
    if errors:
        fail(errors)

    for x in sorted(live_ids - ids):
        errors.append(f"live.txt names '{x}', which is not an id in entries.json")
    if errors:
        fail(errors)

    # Only live entries are published: status "live" (the default), or listed in live.txt.
    entries = [e for e in entries if e.get("status", "live") == "live" or e["id"] in live_ids]
    ids = {e["id"] for e in entries}
    published = []
    for e in entries:
        p = {k: v for k, v in e.items() if k not in ("allow", "status")}
        if e.get("forgotten"):
            p = {"id": e["id"], "name": FORGOTTEN_NAME, "type": e["type"], "forgotten": True,
                 "summary": "Something was written here. You cannot remember what.", "seen": e.get("seen", "")}
        published.append(p)
    for p in published:
        if "related" in p:
            p["related"] = [r for r in p["related"] if r in ids]

    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(os.path.join(out, "img"))
    open(os.path.join(out, ".nojekyll"), "w").close()
    for p in published:
        for im in p.get("images", []):
            shutil.copy(os.path.join(ROOT, "codex", im["src"]), os.path.join(out, im["src"]))

    page = open(os.path.join(ROOT, "codex", "index.html")).read()
    title = cfg["title"]
    page = page.replace("<title>Obliviosa Codex</title>", f"<title>{title}</title>")
    page = re.sub(r'<meta name="description"[^>]*>', f'<meta name="description" content="{cfg["subtitle"]}">', page)
    head = ("<script>window.CODEX_MODE = \"player\"; window.CODEX_TITLE = " + json.dumps(title) +
            "; window.CODEX_SUBTITLE = " + json.dumps(cfg["subtitle"]) + ";</script>\n")
    page = page.replace('<script src="things.js"></script>', head + '<script src="things.js"></script>')
    open(os.path.join(out, "index.html"), "w").write(page)
    with open(os.path.join(out, "things.js"), "w") as f:
        f.write("// Generated by player/build.py. Edit player/entries.json instead.\nwindow.THINGS = ")
        json.dump(published, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    print(f"Built {len(published)} live entries into {out}")


main()
